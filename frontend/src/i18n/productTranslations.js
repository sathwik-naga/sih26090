/**
 * Helper to get localized product data with graceful fallback to English/original values
 */
export function getLocalizedProduct(product, langCode) {
  if (!product) return null;
  const prodTrans = PRODUCT_TRANSLATIONS[product.id];
  const langTrans = prodTrans ? (prodTrans[langCode] || prodTrans['en']) : null;

  if (!langTrans) {
    return product;
  }

  return {
    ...product,
    name: langTrans.name || product.name,
    category: langTrans.category || product.category,
    materials: langTrans.materials || product.materials,
    story: langTrans.story || product.story,
    careInstructions: langTrans.careInstructions || product.careInstructions,
  };
}

export default PRODUCT_TRANSLATIONS;
