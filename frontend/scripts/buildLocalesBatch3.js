import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import en from '../src/i18n/locales/en.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const localesDir = path.join(__dirname, '../src/i18n/locales');

function writeLocale(code, data) {
  const result = {};
  for (const [sectionKey, sectionObj] of Object.entries(en)) {
    result[sectionKey] = {};
    const langSec = data[sectionKey] || {};
    for (const [key, defaultVal] of Object.entries(sectionObj)) {
      result[sectionKey][key] = (langSec[key] !== undefined && langSec[key] !== '') ? langSec[key] : defaultVal;
    }
  }
  const content = `// src/i18n/locales/${code}.js\nexport default ${JSON.stringify(result, null, 2)};\n`;
  fs.writeFileSync(path.join(localesDir, `${code}.js`), content, 'utf8');
  console.log(`✓ Generated ${code}.js`);
}

